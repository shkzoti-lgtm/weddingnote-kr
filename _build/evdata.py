def parse_addr(addr):
    """주소 문자열에서 구·도로명·건물·층·건물유형을 뽑는다."""
    a = (addr or "").strip()
    d = {"raw": a, "gu": "", "road": "", "no": "", "floor": "", "kind": "", "kind_note": "", "bldg": ""}
    m = _GU.search(a)
    if m: d["gu"] = m.group(1)
    m = _ROAD.search(a)
    if m:
        d["road"] = m.group(1)
        d["no"] = (m.group(2) or "").strip()
    m = _FLOOR.search(a)
    if m: d["floor"] = m.group(1).replace(" ", "")
    for keys, kind, note in BUILDING_KIND:
        if any(k in a for k in keys):
            d["kind"], d["kind_note"] = kind, note
            break
    # 건물명 추정: 층 표기 앞의 마지막 토큰 덩어리
    body = _FLOOR.sub("", a).strip()
    toks = body.split()
    if toks:
        cand = [t for t in toks[2:] if not re.fullmatch(r"[0-9-]+", t)]
        d["bldg"] = " ".join(cand[-2:]) if cand else ""
    return d


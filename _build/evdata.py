def date_facts(start, end):
    try:
        s = datetime.date.fromisoformat(start); e = datetime.date.fromisoformat(end)
    except Exception:
        return {}
    days = (e - s).days + 1
    return {"s": s, "e": e, "days": days,
            "wd_s": WD[s.weekday()], "wd_e": WD[e.weekday()],
            "weekend": s.weekday() >= 5 or e.weekday() >= 5,
            "long": days >= 7, "peak": PEAK_MONTH.get(s.month, ""), "month": s.month}

